// Конфиг лендингов «разбора» под группы болей (ТЗ 2026-09-06).
// Один шаблон RazborTemplate + разные тексты на группу. Общие блоки
// («Как проходит разбор», «Кто я», форма, футер, FAQ) — в шаблоне, здесь
// только то, что различается: hero, карточки «Узнаёте себя?», «Что я делаю».
//
// slug = source_tag формы и часть deep-link ?start=<slug>_<id>. Пустой slug
// (общий /razbor) → source_tag 'landing', deep-link ?start=landing[_<id>].

export interface RazborPain {
  title: string;
  text: string;
}

export interface RazborConfig {
  slug: '' | 'zvonki' | 'ocheredi' | 'zakazy';
  hero: {
    titleTop: string; // обычная строка заголовка
    titleAccent: string; // строка с градиентом
    sub: string;
  };
  painsTitle: string;
  pains: RazborPain[]; // ровно 4 карточки «Узнаёте себя?»
  solutions: string[]; // ровно 4 пункта «Что я делаю»
}

